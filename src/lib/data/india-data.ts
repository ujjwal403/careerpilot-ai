/**
 * Returns universities for a given Indian State, prioritizing the selected City.
 * If no state is given, returns the master list of all premier Indian universities.
 */
export function getUniversitiesForState(stateName?: string, cityName?: string): string[] {
  const baseList = (stateName && STATE_UNIVERSITIES_MAP[stateName])
    ? STATE_UNIVERSITIES_MAP[stateName]
    : ALL_PREMIER_INDIAN_COLLEGES

  if (!cityName || !cityName.trim()) {
    return baseList
  }

  const cleanCity = cityName.trim().toLowerCase().split(' ')[0] // e.g. "Pune", "Bengaluru", "Noida"
  if (cleanCity.length < 3) return baseList

  const cityMatches: string[] = []
  const otherMatches: string[] = []

  for (const uni of baseList) {
    if (uni.toLowerCase().includes(cleanCity)) {
      cityMatches.push(uni)
    } else {
      otherMatches.push(uni)
    }
  }

  return [...cityMatches, ...otherMatches]
}

/**
 * Returns courses / branches for a given degree
 */
export function getSpecializationsForDegree(degreeName: string): string[] {
  if (degreeName && DEGREE_SPECIALIZATIONS_MAP[degreeName]) {
    return DEGREE_SPECIALIZATIONS_MAP[degreeName]
  }
  for (const [key, list] of Object.entries(DEGREE_SPECIALIZATIONS_MAP)) {
    if (key.toLowerCase().includes(degreeName.toLowerCase()) || degreeName.toLowerCase().includes(key.toLowerCase().split(' ')[0])) {
      return list
    }
  }
  return DEGREE_SPECIALIZATIONS_MAP['B.Tech / B.E. (Bachelor of Technology / Engineering)']
}
